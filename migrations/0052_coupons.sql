-- Unique coupon codes: a coupon is a pool of single-use codes. Each person gets their own code,
-- claimed when a message is about to render or a sign-up form hands one out (see src/features/coupons).
-- A code given to a person is theirs for good: codes never go back to the pool.

CREATE TABLE coupons (
    id                  uuid PRIMARY KEY,
    account_id          uuid NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    -- What templates use: {% coupon_code 'NAME' %}. Can't change after creation.
    name                text NOT NULL,
    description         text NOT NULL DEFAULT '',
    -- 'uploaded' (codes made in the store) or 'generated' (DumbMail made them from `pattern`).
    source              text NOT NULL DEFAULT 'uploaded',
    -- Generated coupons: {"prefix": "WELCOME-", "length": 8, "alphabet": "letters_digits"}.
    pattern             jsonb,
    -- Codes expire on a fixed date, or N days after they're first sent (or never).
    expires_at          timestamptz,
    expires_after_days  integer,
    -- false: a person gets the same code every time (reminders, resends). true: a new code per send.
    new_code_each_time  boolean NOT NULL DEFAULT false,
    -- Alert when fewer than this many codes are left.
    low_stock_threshold integer,
    -- Most codes sign-up forms may hand out per hour, so made-up sign-ups can't drain the pool.
    form_codes_per_hour integer NOT NULL DEFAULT 200,
    -- Every code ever added (codes are never deleted one by one).
    codes_total         bigint NOT NULL DEFAULT 0,
    -- Codes still to be generated by the background job.
    generate_pending    integer NOT NULL DEFAULT 0,
    -- Set (and the owner alerted, once) when a send or sign-up found no code left; cleared only when codes are added.
    out_of_codes_at     timestamptz,
    low_stock_alerted_at timestamptz,
    low_stock_checked_at timestamptz,
    -- Deleted coupons vanish at once; a job removes their codes in batches, then the row.
    deleted_at          timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX coupons_account_name_idx ON coupons (account_id, lower(name)) WHERE deleted_at IS NULL;
CREATE INDEX coupons_low_stock_idx ON coupons (low_stock_checked_at NULLS FIRST) WHERE low_stock_threshold IS NOT NULL AND deleted_at IS NULL;

CREATE TABLE coupon_codes (
    id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id     uuid NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    coupon_id      uuid NOT NULL REFERENCES coupons(id) ON DELETE CASCADE,
    -- As uploaded (ASCII letters, digits, - and _), and upper-cased for case-insensitive matching.
    code           text NOT NULL,
    code_norm      text NOT NULL,
    -- 'available' or 'assigned' (given to someone; never goes back).
    status         text NOT NULL DEFAULT 'available',
    profile_id     uuid REFERENCES profiles(id) ON DELETE SET NULL,
    -- NULL: the person's one code for this coupon. Otherwise the send it's for, for coupons that give
    -- a new code each time ('campaign:<message id>', 'flow:<run id>:<step id>', 'form:<form id>').
    send_key       text,
    -- 'message', 'form' or 'store' (created in the store for this person).
    assigned_via   text,
    -- The first message it was meant for, or the form that gave it.
    message_id     uuid,
    form_id        uuid,
    -- Hashed visitor address of a form sign-up, for the per-visitor limit.
    ip_hash        text,
    assigned_at    timestamptz,
    -- When a message carrying it was first handed to the provider, or a form first showed it.
    delivered_at   timestamptz,
    expires_at     timestamptz,
    -- A verified redemption: an order recorded by the API, MCP or a store integration.
    redeemed_at    timestamptz,
    order_event_id uuid,
    -- The order's value, on one redemption per order (so an order is counted once).
    order_value    double precision,
    -- Unverified evidence: an order recorded by the website script (a visitor could have made it up).
    browser_order_event_id uuid,
    browser_order_at       timestamptz,
    browser_order_value    double precision,
    created_at     timestamptz NOT NULL DEFAULT now()
);
-- text_pattern_ops also serves prefix searches (code_norm LIKE 'ABC%').
CREATE UNIQUE INDEX coupon_codes_code_idx ON coupon_codes (coupon_id, code_norm text_pattern_ops);
-- One code per person per coupon, or per person per send for "new code each time".
CREATE UNIQUE INDEX coupon_codes_person_idx ON coupon_codes (coupon_id, profile_id) WHERE profile_id IS NOT NULL AND send_key IS NULL;
CREATE UNIQUE INDEX coupon_codes_send_idx ON coupon_codes (coupon_id, profile_id, send_key) WHERE profile_id IS NOT NULL AND send_key IS NOT NULL;
CREATE INDEX coupon_codes_available_idx ON coupon_codes (coupon_id, id) WHERE status = 'available';
CREATE INDEX coupon_codes_page_idx ON coupon_codes (coupon_id, id);
CREATE INDEX coupon_codes_holder_idx ON coupon_codes (profile_id, code_norm) WHERE profile_id IS NOT NULL;
CREATE INDEX coupon_codes_delivered_idx ON coupon_codes (coupon_id, delivered_at) WHERE delivered_at IS NOT NULL;
CREATE INDEX coupon_codes_redeemed_idx ON coupon_codes (coupon_id, redeemed_at) WHERE redeemed_at IS NOT NULL;
CREATE UNIQUE INDEX coupon_codes_order_value_idx ON coupon_codes (order_event_id) WHERE order_value IS NOT NULL;
CREATE INDEX coupon_codes_form_idx ON coupon_codes (coupon_id, assigned_at) WHERE assigned_via = 'form';
CREATE INDEX coupon_codes_ip_idx ON coupon_codes (ip_hash, assigned_at) WHERE ip_hash IS NOT NULL;

-- A deleted person's codes stay used, but lose every link to them.
CREATE FUNCTION coupon_codes_forget_person() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.send_key := NULL;
    NEW.message_id := NULL;
    NEW.ip_hash := NULL;
    NEW.order_event_id := NULL;
    NEW.browser_order_event_id := NULL;
    RETURN NEW;
END $$;
CREATE TRIGGER coupon_codes_forget_person BEFORE UPDATE ON coupon_codes
    FOR EACH ROW WHEN (OLD.profile_id IS NOT NULL AND NEW.profile_id IS NULL) EXECUTE FUNCTION coupon_codes_forget_person();

-- Sends waiting because a coupon ran out of codes: one row per campaign or flow, cleared when codes are added.
CREATE TABLE coupon_holds (
    coupon_id   uuid NOT NULL REFERENCES coupons(id) ON DELETE CASCADE,
    -- 'campaign:<id>' or 'flow:<id>'.
    subject     text NOT NULL,
    account_id  uuid NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    campaign_id uuid REFERENCES campaigns(id) ON DELETE CASCADE,
    flow_id     uuid REFERENCES flows(id) ON DELETE CASCADE,
    first_at    timestamptz NOT NULL DEFAULT now(),
    last_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (coupon_id, subject)
);
CREATE INDEX coupon_holds_account_idx ON coupon_holds (account_id);

-- A double opt-in sign-up that earned a code: the coupon its form had when it was submitted, given
-- once the address is confirmed (only sign-ups that created the person earn one).
CREATE TABLE coupon_signup_grants (
    confirmation_id uuid PRIMARY KEY REFERENCES optin_confirmations(id) ON DELETE CASCADE,
    account_id      uuid NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    coupon_id       uuid NOT NULL REFERENCES coupons(id) ON DELETE CASCADE,
    form_id         uuid NOT NULL,
    profile_id      uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
    code_id         bigint REFERENCES coupon_codes(id) ON DELETE SET NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
);

-- One upload or generation run at a time per account (a lease, so no connection is held meanwhile).
CREATE TABLE coupon_work_leases (
    account_id uuid PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    token      uuid NOT NULL,
    started_at timestamptz NOT NULL DEFAULT now()
);

-- Redemptions are matched by a scheduler step that reads new order events after a cursor (event ids
-- are time-ordered), re-reading a short overlap and skipping events it has already handled.
CREATE TABLE coupon_reconcile (
    id         smallint PRIMARY KEY CHECK (id = 1),
    cursor_id  uuid NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE coupon_orders_seen (
    event_id uuid PRIMARY KEY,
    seen_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX coupon_orders_seen_at_idx ON coupon_orders_seen (seen_at);
